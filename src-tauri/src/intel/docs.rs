//! Deterministic architecture document generated from the code index. No AI required.

use super::graph::Graph;

pub struct DocInput<'a> {
    pub name: &'a str,
    pub summary: &'a str,
    pub frameworks: Vec<String>,
    /// (language, files, lines)
    pub languages: Vec<(String, u64, u64)>,
    pub modules: &'a Graph,
    /// (path, importer count), most imported first.
    pub hotspots: Vec<(String, u32)>,
    pub entry_points: Vec<String>,
    /// (package, importing file count), most used first.
    pub externals: Vec<(String, u32)>,
    pub symbol_count: u64,
    pub generated_at: &'a str,
}

fn mermaid_id(id: &str) -> String {
    let s: String = id.chars().map(|c| if c.is_ascii_alphanumeric() { c } else { '_' }).collect();
    format!("m_{s}")
}

pub fn render(d: &DocInput) -> String {
    let mut o = String::new();
    let p = |o: &mut String, s: &str| {
        o.push_str(s);
        o.push('\n');
    };
    p(&mut o, &format!("# {} — Architecture\n", d.name));
    p(&mut o, &format!("_Generated by NEXUS from the code index on {}. Regenerate after significant changes._\n", d.generated_at));

    p(&mut o, "## Overview\n");
    p(&mut o, if d.summary.is_empty() { "No analysis summary is available." } else { d.summary });
    if !d.frameworks.is_empty() {
        p(&mut o, &format!("\n**Stack:** {}", d.frameworks.join(", ")));
    }
    p(&mut o, "");
    if !d.languages.is_empty() {
        p(&mut o, "| Language | Files | Lines |\n| --- | ---: | ---: |");
        for (name, files, lines) in &d.languages {
            p(&mut o, &format!("| {name} | {files} | {lines} |"));
        }
        p(&mut o, "");
    }

    let modules: Vec<_> = d.modules.nodes.iter().filter(|n| n.kind == "module").collect();
    p(&mut o, "## Modules\n");
    if modules.is_empty() {
        p(&mut o, "No indexed source files were found (indexed languages: Rust, TypeScript, JavaScript, Python, Go).\n");
    } else {
        p(&mut o, "| Module | Files | Lines | Depends on | Used by |\n| --- | ---: | ---: | ---: | ---: |");
        for n in &modules {
            p(&mut o, &format!("| `{}` | {} | {} | {} | {} |", n.id, n.files, n.lines, n.fan_out, n.fan_in));
        }
        p(&mut o, "");
        let edges: Vec<_> = d.modules.edges.iter().filter(|e| !e.to.starts_with("ext:")).collect();
        if !edges.is_empty() {
            p(&mut o, "### Module dependencies\n\n```mermaid\ngraph LR");
            for n in &modules {
                p(&mut o, &format!("    {}[\"{}\"]", mermaid_id(&n.id), n.id));
            }
            for e in edges {
                p(&mut o, &format!("    {} -->|{}| {}", mermaid_id(&e.from), e.weight, mermaid_id(&e.to)));
            }
            p(&mut o, "```\n\nEdge labels are the number of import statements.\n");
        }
    }

    p(&mut o, "## Dependency cycles\n");
    if d.modules.cycles.is_empty() {
        p(&mut o, "None detected between modules.\n");
    } else {
        for c in &d.modules.cycles {
            p(&mut o, &format!("- {}", c.iter().map(|m| format!("`{m}`")).collect::<Vec<_>>().join(" ↔ ")));
        }
        p(&mut o, "\nModules in a cycle cannot be understood, tested or changed independently.\n");
    }

    if !d.entry_points.is_empty() {
        p(&mut o, "## Entry points\n");
        for e in &d.entry_points {
            p(&mut o, &format!("- `{e}`"));
        }
        p(&mut o, "");
    }
    if !d.hotspots.is_empty() {
        p(&mut o, "## Most depended-on files\n\nChanges here have the widest impact.\n\n| File | Imported by |\n| --- | ---: |");
        for (path, n) in &d.hotspots {
            p(&mut o, &format!("| `{path}` | {n} files |"));
        }
        p(&mut o, "");
    }
    if !d.externals.is_empty() {
        p(&mut o, "## External dependencies in use\n\n| Package | Imported by |\n| --- | ---: |");
        for (name, n) in &d.externals {
            p(&mut o, &format!("| `{name}` | {n} files |"));
        }
        p(&mut o, "");
    }
    p(
        &mut o,
        &format!(
            "---\n{} symbols indexed. Symbols and imports are extracted with line-based rules, so unusual constructs can be missed.",
            d.symbol_count
        ),
    );
    o
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::intel::graph::{build, ImportRow};

    #[test]
    fn renders_modules_graph_and_cycles() {
        let files: Vec<(String, u64)> = ["src/a.ts", "lib/b.ts"].iter().map(|p| (p.to_string(), 5)).collect();
        let imports = [
            ImportRow { from: "src/a.ts".into(), target: "lib/b.ts".into(), external: false },
            ImportRow { from: "lib/b.ts".into(), target: "src/a.ts".into(), external: false },
        ];
        let g = build(&files, &imports, false, 1, false, 50);
        let doc = render(&DocInput {
            name: "demo",
            summary: "A demo.",
            frameworks: vec!["React".into()],
            languages: vec![("TypeScript".into(), 2, 10)],
            modules: &g,
            hotspots: vec![("lib/b.ts".into(), 1)],
            entry_points: vec!["src/a.ts".into()],
            externals: vec![("react".into(), 1)],
            symbol_count: 3,
            generated_at: "2026-01-01",
        });
        for expected in [
            "# demo — Architecture",
            "**Stack:** React",
            "| `lib` | 1 | 5 | 1 | 1 |",
            "```mermaid",
            "m_src -->|1| m_lib",
            "`lib` ↔ `src`",
            "- `src/a.ts`",
            "| `react` | 1 files |",
        ] {
            assert!(doc.contains(expected), "missing {expected:?} in:\n{doc}");
        }
    }
}
